	public static function list_columns( $columns ) {
		list( $key, $type ) = self::type_for_post_type( get_current_screen()->post_type );
		$result             = array(
			'cb'    => $columns['cb'],
			'title' => 'newsletter' === $key ? 'Email' : 'Entry',
		);
		foreach ( $type['columns'] as $field ) {
			$result[ 'mr_' . $field ] = $type['fields'][ $field ][0];
		}
		$result['mr_status']   = 'Status';
		// Own column: WordPress labels private posts' dates "Last Modified".
		$result['mr_received'] = 'Received';
		return $result;
	}

	public static function list_column_value( $column, $post_id ) {
		if ( 0 !== strpos( $column, 'mr_' ) ) {
			return;
		}
		$field = substr( $column, 3 );
		if ( 'received' === $field ) {
			echo esc_html( get_the_date( 'j M Y, g:i a', $post_id ) );
			return;
		}
		if ( 'status' === $field ) {
			list( , $type ) = self::type_for_post_type( get_post_type( $post_id ) );
			$status         = self::meta( $post_id, 'status' );
			echo esc_html( $type['statuses'][ $status ] ?? $status );
			return;
		}
		echo esc_html( self::meta( $post_id, $field ) );
	}

	public static function status_filter( $post_type ) {
		list( $key, $type ) = self::type_for_post_type( $post_type );
		if ( ! $type ) {
			return;
		}
		$current = isset( $_GET['mr_status'] ) ? sanitize_key( wp_unslash( $_GET['mr_status'] ) ) : '';
		echo '<select name="mr_status"><option value="">All statuses</option>';
		foreach ( $type['statuses'] as $value => $label ) {
			printf( '<option value="%s"%s>%s</option>', esc_attr( $value ), selected( $current, $value, false ), esc_html( $label ) );
		}
		echo '</select>';

		if ( 'newsletter' === $key && current_user_can( 'edit_others_mr_entries' ) ) {
			$url = wp_nonce_url( admin_url( 'admin-post.php?action=mr_export_subscribers' ), 'mr_export_subscribers' );
			printf( ' <a class="button" href="%s">Export CSV</a>', esc_url( $url ) );
		}
	}

	public static function apply_status_filter( $query ) {
		if ( ! $query->is_main_query() || empty( $_GET['mr_status'] ) ) {
			return;
		}
		list( , $type ) = self::type_for_post_type( $query->get( 'post_type' ) );
		if ( $type ) {
			$query->set( 'meta_key', self::META . 'status' );
			$query->set( 'meta_value', sanitize_key( wp_unslash( $_GET['mr_status'] ) ) );
		}
	}

	/** No Quick Edit — it would expose post status/visibility controls that don't apply here. */
	public static function row_actions( $actions, $post ) {
		list( , $type ) = self::type_for_post_type( $post->post_type );
		if ( $type ) {
			unset( $actions['inline hide-if-no-js'] );
			if ( isset( $actions['edit'] ) ) {
				$actions['edit'] = str_replace( '>Edit<', '>View<', $actions['edit'] );
			}
		}
		return $actions;
	}

	/** Every entry is private, so the "— Private" label on each row is noise. */
	public static function post_states( $states, $post ) {
		list( , $type ) = self::type_for_post_type( $post->post_type );
		if ( $type ) {
			unset( $states['private'] );
		}
		return $states;
	}

	public static function export_subscribers() {
		if ( ! current_user_can( 'edit_others_mr_entries' ) ) {
			wp_die( 'You are not allowed to export subscribers.', 403 );
		}
		check_admin_referer( 'mr_export_subscribers' );

		$ids = get_posts(
			array(
				'post_type'      => 'mr_subscriber',
				'post_status'    => 'any',
				'posts_per_page' => -1,
				'fields'         => 'ids',
				'orderby'        => 'date',
				'order'          => 'ASC',
			)
		);

		nocache_headers();
		header( 'Content-Type: text/csv; charset=utf-8' );
		header( 'Content-Disposition: attachment; filename=dede-law-subscribers-' . gmdate( 'Y-m-d' ) . '.csv' );
		$out = fopen( 'php://output', 'w' );
		fputcsv( $out, array( 'Email', 'First name', 'Status', 'Subscribed on' ) );
		foreach ( $ids as $id ) {
			fputcsv( $out, array( self::meta( $id, 'email' ), self::meta( $id, 'firstName' ), self::meta( $id, 'status' ), get_the_date( 'Y-m-d', $id ) ) );
		}
		fclose( $out );
		exit;
	}

