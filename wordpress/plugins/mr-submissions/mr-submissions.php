	public static function register_routes() {
		register_rest_route(
			'mr/v1',
			'/submissions/(?P<type>dispute|contact|training|newsletter)',
			array(
				'methods'             => 'POST',
				'callback'            => array( __CLASS__, 'handle_submission' ),
				'permission_callback' => function () {
					return current_user_can( self::SUBMIT_CAP );
				},
			)
		);
	}

	public static function handle_submission( WP_REST_Request $request ) {
		$types  = self::types();
		$key    = $request['type'];
		$type   = $types[ $key ];
		$params = $request->get_json_params();
		$params = is_array( $params ) ? $params : array();

		$values = array();
		$errors = array();

		foreach ( $type['fields'] as $field => $definition ) {
			list( , $max, $required, $kind ) = $definition;
			$raw = isset( $params[ $field ] ) && is_scalar( $params[ $field ] ) ? (string) $params[ $field ] : '';

			if ( 'textarea' === $kind ) {
				$value = sanitize_textarea_field( $raw );
			} elseif ( 'email' === $kind ) {
				$value = sanitize_email( $raw );
			} else {
				$value = sanitize_text_field( $raw );
			}
			$value = mb_substr( trim( $value ), 0, $max );

			if ( $required && '' === $value ) {
				$errors[ $field ] = 'This field is required.';
			} elseif ( 'email' === $kind && '' !== $value && ! is_email( $value ) ) {
				$errors[ $field ] = 'Please enter a valid email address.';
			}
			$values[ $field ] = $value;
		}

		if ( $errors ) {
			return new WP_Error( 'mr_invalid', 'Some fields are invalid.', array( 'status' => 422, 'errors' => $errors ) );
		}

		// Newsletter: one entry per email address — re-subscribing updates it.
		if ( 'newsletter' === $key ) {
			$existing = get_posts(
				array(
					'post_type'      => $type['post_type'],
					'post_status'    => 'any',
					'posts_per_page' => 1,
					'fields'         => 'ids',
					'meta_key'       => self::META . 'email',
					'meta_value'     => $values['email'],
				)
			);
			if ( $existing ) {
				if ( '' !== $values['firstName'] ) {
					update_post_meta( $existing[0], self::META . 'firstName', $values['firstName'] );
				}
				update_post_meta( $existing[0], self::META . 'status', 'subscribed' );
				return new WP_REST_Response( array( 'ok' => true, 'id' => $existing[0], 'existing' => true ), 200 );
			}
		}

		$title_parts = array();
		foreach ( $type['title'] as $field ) {
			if ( '' !== $values[ $field ] ) {
				$title_parts[] = $values[ $field ];
			}
		}

		$post_id = wp_insert_post(
			array(
				'post_type'   => $type['post_type'],
				'post_status' => 'private',
				'post_title'  => implode( ' — ', $title_parts ),
			),
			true
		);
		if ( is_wp_error( $post_id ) ) {
			return new WP_Error( 'mr_save_failed', 'The entry could not be saved.', array( 'status' => 500 ) );
		}

		foreach ( $values as $field => $value ) {
			update_post_meta( $post_id, self::META . $field, $value );
		}
		update_post_meta( $post_id, self::META . 'status', array_key_first( $type['statuses'] ) );

		self::notify( $key, $type, $post_id, $values );

		return new WP_REST_Response( array( 'ok' => true, 'id' => $post_id ), 201 );
	}

	/** Emails the team. A failed email never fails the submission. */
	private static function notify( $key, $type, $post_id, $values ) {
		if ( empty( $type['notify'] ) ) {
			return;
		}
		$to = MR_Settings::notify_email( $type['notify'] );

		$lines = array( 'A new ' . strtolower( $type['singular'] ) . ' has arrived from the website.', '' );
		foreach ( $type['fields'] as $field => $definition ) {
			if ( in_array( $field, $type['private'], true ) || '' === $values[ $field ] ) {
				continue;
			}
			$lines[] = $definition[0] . ': ' . $values[ $field ];
		}
		if ( $type['private'] ) {
			$lines[] = '';
			$lines[] = 'For confidentiality, the full details are only available inside WordPress.';
		}
		$lines[] = '';
		$lines[] = 'Open it: ' . admin_url( 'post.php?post=' . $post_id . '&action=edit' );

		$reply_to = is_email( $values['email'] ?? '' ) ? array( 'Reply-To: ' . $values['email'] ) : array();
		// Raw title: get_the_title() would prefix "Private:".
		wp_mail( $to, 'New ' . strtolower( $type['singular'] ) . ': ' . get_post_field( 'post_title', $post_id ), implode( "\n", $lines ), $reply_to );
	}

