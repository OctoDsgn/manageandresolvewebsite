	/** Grants capabilities and creates the API-only role (re-runs when the version changes). */
	public static function maybe_install() {
		if ( get_option( 'mr_submissions_version' ) === self::VERSION ) {
			return;
		}

		$admin = get_role( 'administrator' );
		if ( $admin ) {
			foreach ( self::MANAGE_CAPS as $cap ) {
				$admin->add_cap( $cap );
			}
		}

		if ( ! get_role( self::SUBMITTER_ROLE ) ) {
			add_role( self::SUBMITTER_ROLE, 'Website forms (API only)', array( 'read' => true ) );
		}
		get_role( self::SUBMITTER_ROLE )->add_cap( self::SUBMIT_CAP );

		update_option( 'mr_submissions_version', self::VERSION );
	}

	private static function type_for_post_type( $post_type ) {
		foreach ( self::types() as $key => $type ) {
			if ( $type['post_type'] === $post_type ) {
				return array( $key, $type );
			}
		}
		return array( null, null );
	}

	private static function meta( $post_id, $field ) {
		return (string) get_post_meta( $post_id, self::META . $field, true );
	}

