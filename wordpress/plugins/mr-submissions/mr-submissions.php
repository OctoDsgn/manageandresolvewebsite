			printf( '<option value="%s"%s>%s</option>', esc_attr( $value ), selected( $status, $value, false ), esc_html( $label ) );
		}
		echo '</select></p>';

		echo '<p><label for="mr_notes_field"><strong>Internal notes</strong></label><br />';
		printf(
			'<textarea id="mr_notes_field" name="mr_notes_field" rows="6" style="width:100%%">%s</textarea></p>',
			esc_textarea( self::meta( $post->ID, 'notes' ) )
		);
		echo '<p class="description">Only visible to your team. Click Update to save.</p>';
	}

	public static function save_meta_box( $post_id, $post ) {
		list( , $type ) = self::type_for_post_type( $post->post_type );
		if ( ! $type || ! isset( $_POST[ self::NONCE ] ) ) {
			return;
		}
		if ( ! wp_verify_nonce( sanitize_text_field( wp_unslash( $_POST[ self::NONCE ] ) ), self::NONCE ) ) {
			return;
		}
		if ( defined( 'DOING_AUTOSAVE' ) && DOING_AUTOSAVE ) {
			return;
		}
		if ( ! current_user_can( 'edit_post', $post_id ) ) {
			return;
		}

		$status = isset( $_POST['mr_status_field'] ) ? sanitize_key( wp_unslash( $_POST['mr_status_field'] ) ) : '';
		if ( isset( $type['statuses'][ $status ] ) ) {
			update_post_meta( $post_id, self::META . 'status', $status );
		}
		if ( isset( $_POST['mr_notes_field'] ) ) {
			update_post_meta( $post_id, self::META . 'notes', sanitize_textarea_field( wp_unslash( $_POST['mr_notes_field'] ) ) );
		}
	}
