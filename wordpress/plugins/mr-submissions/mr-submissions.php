	public static function render_details( $post ) {
		list( , $type ) = self::type_for_post_type( $post->post_type );
		echo '<table class="widefat striped"><tbody>';
		foreach ( $type['fields'] as $field => $definition ) {
			$value = self::meta( $post->ID, $field );
			if ( 'email' === $definition[3] && $value ) {
				$display = sprintf( '<a href="mailto:%1$s">%1$s</a>', esc_html( $value ) );
			} elseif ( 'textarea' === $definition[3] ) {
				$display = nl2br( esc_html( $value ) );
			} else {
				$display = esc_html( $value );
			}
			printf( '<tr><th style="width:30%%">%s</th><td>%s</td></tr>', esc_html( $definition[0] ), $display ? $display : '<span style="color:#999">—</span>' );
		}
		printf( '<tr><th>Received</th><td>%s</td></tr>', esc_html( get_the_date( 'j F Y, g:i a', $post ) ) );
		echo '</tbody></table>';
	}

