			foreach ( self::types() as $type ) {
				$post_type = $type['post_type'];
				add_filter( "manage_{$post_type}_posts_columns", array( __CLASS__, 'list_columns' ) );
				add_action( "manage_{$post_type}_posts_custom_column", array( __CLASS__, 'list_column_value' ), 10, 2 );
			}
		}
	}

